"""
Exports etymology.db (built by relational_database.py) into a Cypher script
that loads the same data into Neo4j as a property graph.

Run `python relational_database.py` first to (re)build etymology.db, then
`python export_to_neo4j.py` to regenerate graph_export.cypher. Load the
result into Neo4j Browser, cypher-shell, or Neo4j Desktop's "run script"
feature - every statement uses MERGE, so it's safe to re-run against the
same database without creating duplicates.

Node labels: Word, Language, Category, Scheme, Source, Etymology.
DEVELOPED_INTO edges are reified as :Etymology nodes (edge_id, is_diachronic)
rather than plain relationships, because a single etymological claim can be
cited by multiple sources with different loci/notes, and Neo4j relationships
cannot be the target of another relationship - citations need a node to
attach to. Every other relationship type (HAS_WORD, CONNECTED_TO,
RESOLVES_INTO, HAS_CATEGORY) stays a plain Neo4j relationship since nothing
else needs to attach provenance to them.
"""

import sqlite3

con = sqlite3.connect("etymology.db")
cur = con.cursor()

lines = [
    "// Generated by export_to_neo4j.py - run with cypher-shell or paste into Neo4j Browser.",
    "// Every statement uses MERGE, so this is safe to re-run.",
    "",
    "CREATE CONSTRAINT word_id IF NOT EXISTS FOR (w:Word) REQUIRE w.word_id IS UNIQUE;",
    "CREATE CONSTRAINT language_id IF NOT EXISTS FOR (l:Language) REQUIRE l.word_id IS UNIQUE;",
    "CREATE CONSTRAINT category_id IF NOT EXISTS FOR (c:Category) REQUIRE c.category_id IS UNIQUE;",
    "CREATE CONSTRAINT scheme_id IF NOT EXISTS FOR (s:Scheme) REQUIRE s.scheme_id IS UNIQUE;",
    "CREATE CONSTRAINT source_id IF NOT EXISTS FOR (so:Source) REQUIRE so.source_id IS UNIQUE;",
    "CREATE CONSTRAINT etymology_id IF NOT EXISTS FOR (e:Etymology) REQUIRE e.edge_id IS UNIQUE;",
    "",
]


def esc(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


# --- Word / Language nodes (both from the `words` table) ---
lines.append("// --- Word / Language nodes ---")
word_node_ids = set()
for word_id, node_type, csv_id, word, meaning, category, tags in cur.execute(
    "SELECT word_id, node_type, id, word, meaning, category, tags FROM words"
):
    if node_type == "WORD":
        word_node_ids.add(word_id)
        lines.append(
            f"MERGE (w:Word {{word_id: {word_id}}}) "
            f"SET w.csv_id = {esc(csv_id)}, w.word = {esc(word)}, "
            f"w.meaning = {esc(meaning)}, w.category = {esc(category)};"
        )
    else:  # LANGUAGE
        lines.append(f"MERGE (l:Language {{word_id: {word_id}}}) SET l.name = {esc(word)};")
lines.append("")

# --- Category nodes ---
lines.append("// --- Category nodes ---")
for category_id, label in cur.execute("SELECT category_id, label FROM semantic_categories"):
    lines.append(f"MERGE (c:Category {{category_id: {category_id}}}) SET c.label = {esc(label)};")
lines.append("")

# --- Scheme nodes ---
lines.append("// --- Scheme nodes ---")
for scheme_id, name in cur.execute("SELECT scheme_id, name FROM semantic_schemes"):
    lines.append(f"MERGE (s:Scheme {{scheme_id: {scheme_id}}}) SET s.name = {esc(name)};")
lines.append("")

# --- Source nodes ---
lines.append("// --- Source nodes ---")
for source_id, name, full_name in cur.execute("SELECT source_id, name, full_name FROM sources"):
    lines.append(
        f"MERGE (so:Source {{source_id: {source_id}}}) "
        f"SET so.name = {esc(name)}, so.full_name = {esc(full_name)};"
    )
lines.append("")

# --- Etymology nodes (reified DEVELOPED_INTO edges) + FROM/TO relationships ---
lines.append("// --- Etymology nodes (reified DEVELOPED_INTO edges) ---")
for edge_id, source_word_id, target_word_id, is_diachronic in cur.execute(
    "SELECT edge_id, source_word_id, target_word_id, is_diachronic "
    "FROM edges WHERE relationship_type = 'DEVELOPED_INTO'"
):
    source_label = "Word" if source_word_id in word_node_ids else "Language"
    target_label = "Word" if target_word_id in word_node_ids else "Language"
    lines.append(
        f"MERGE (e:Etymology {{edge_id: {edge_id}}}) "
        f"SET e.is_diachronic = {esc(bool(is_diachronic)) if is_diachronic is not None else 'null'};"
    )
    lines.append(
        f"MATCH (src:{source_label} {{word_id: {source_word_id}}}), (e:Etymology {{edge_id: {edge_id}}}) "
        f"MERGE (src)-[:FROM]->(e);"
    )
    lines.append(
        f"MATCH (e:Etymology {{edge_id: {edge_id}}}), (tgt:{target_label} {{word_id: {target_word_id}}}) "
        f"MERGE (e)-[:TO]->(tgt);"
    )
lines.append("")

# --- HAS_WORD (plain relationship, language -> word) ---
lines.append("// --- HAS_WORD (language -> word); query HAS_WORD in reverse for TAGGED_AS ---")
for source_word_id, target_word_id in cur.execute(
    "SELECT source_word_id, target_word_id FROM edges WHERE relationship_type = 'HAS_WORD'"
):
    lines.append(
        f"MATCH (l:Language {{word_id: {source_word_id}}}), (w:Word {{word_id: {target_word_id}}}) "
        f"MERGE (l)-[:HAS_WORD]->(w);"
    )
lines.append("")

# --- CONNECTED_TO (plain, undirected convention - one relationship per pair) ---
lines.append("// --- CONNECTED_TO (synchronic paradigm siblings); match without an arrow ---")
for source_word_id, target_word_id in cur.execute(
    "SELECT source_word_id, target_word_id FROM edges WHERE relationship_type = 'CONNECTED_TO'"
):
    lines.append(
        f"MATCH (a:Word {{word_id: {source_word_id}}}), (b:Word {{word_id: {target_word_id}}}) "
        f"MERGE (a)-[:CONNECTED_TO]-(b);"
    )
lines.append("")

# --- RESOLVES_INTO (category hierarchy, scheme as an edge property) ---
lines.append("// --- RESOLVES_INTO (category hierarchy, scheme as edge property) ---")
for child_category_id, parent_category_id, scheme_id in cur.execute(
    "SELECT child_category_id, parent_category_id, scheme_id FROM category_edges"
):
    if parent_category_id is None:
        lines.append(
            f"MATCH (c:Category {{category_id: {child_category_id}}}), (s:Scheme {{scheme_id: {scheme_id}}}) "
            f"MERGE (c)-[:RESOLVES_INTO {{scheme_id: {scheme_id}}}]->(s);"
        )
    else:
        lines.append(
            f"MATCH (c:Category {{category_id: {child_category_id}}}), "
            f"(p:Category {{category_id: {int(parent_category_id)}}}) "
            f"MERGE (c)-[:RESOLVES_INTO {{scheme_id: {scheme_id}}}]->(p);"
        )
lines.append("")

# --- HAS_CATEGORY (word -> category membership) ---
lines.append("// --- HAS_CATEGORY (word -> category membership) ---")
for word_id, category_id in cur.execute("SELECT word_id, category_id FROM word_categories"):
    lines.append(
        f"MATCH (w:Word {{word_id: {word_id}}}), (c:Category {{category_id: {category_id}}}) "
        f"MERGE (w)-[:HAS_CATEGORY]->(c);"
    )
lines.append("")

# --- CITED_BY (etymology claim -> source, locus/note as edge properties) ---
lines.append("// --- CITED_BY (etymology claim -> source) ---")
for edge_id, source_id, locus, note in cur.execute(
    "SELECT edge_id, source_id, locus, note FROM citations"
):
    lines.append(
        f"MATCH (e:Etymology {{edge_id: {edge_id}}}), (so:Source {{source_id: {source_id}}}) "
        f"MERGE (e)-[:CITED_BY {{locus: {esc(locus)}, note: {esc(note)}}}]->(so);"
    )

con.close()

with open("graph_export.cypher", "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print(f"Wrote {len(lines)} lines to graph_export.cypher")
